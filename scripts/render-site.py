#!/usr/bin/env python3
"""Builds the app's small website (GitHub Pages, branch gh-pages) from Markdown.

    python3 scripts/render-site.py <out_dir>

Sources (edit these, never the HTML):
    docs/site/index.md, docs/site/index.he.md        -> <out_dir>/index.html
    docs/privacy-policy.md, docs/privacy-policy.he.md -> <out_dir>/privacy-policy.html
    docs/site/favicon.png (when present)              -> <out_dir>/favicon.png

Each page holds English, then Hebrew (right to left, at #he), so the one URL
Play Console takes covers both languages. Plain HTML with inline CSS: no
scripts, fonts, trackers or other outside resources. Also writes .nojekyll so
GitHub Pages serves the files as they are.

Only the files above are written; anything else in <out_dir> (such as .git) is
left alone. Run scripts/test-site.py to check the result.
"""

import html
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SITE_URL = "https://elibukin.github.io/magnifier/"

PAGES = {
    "index.html": ("docs/site/index.md", "docs/site/index.he.md", "Bukin Magnifier",
                   "Bukin Magnifier: a free magnifying glass for Android, with the LED light. "
                   "No internet, no ads."),
    "privacy-policy.html": ("docs/privacy-policy.md", "docs/privacy-policy.he.md",
                            "Bukin Magnifier - Privacy policy",
                            "Privacy policy of Bukin Magnifier: no internet permission, nothing collected."),
}

STYLE = """\
  :root { color-scheme: light dark; --fg: #1b1c1f; --bg: #f7f8fa; --accent: #6b4f00; --rule: #d5d7dc; }
  @media (prefers-color-scheme: dark) { :root { --fg: #e3e4e8; --bg: #15171b; --accent: #ffd54f; --rule: #3a3d44; } }
  body { margin: 0; padding: 24px 16px 48px; background: var(--bg); color: var(--fg);
         font: 16px/1.6 system-ui, -apple-system, "Segoe UI", Roboto, "Noto Sans Hebrew", sans-serif; }
  main { max-width: 720px; margin: 0 auto; }
  nav { max-width: 720px; margin: 0 auto 1rem; font-size: .95rem; }
  nav a { margin-inline-end: 1rem; }
  h1 { font-size: 1.8rem; margin: 0 0 1rem; }
  h2 { font-size: 1.2rem; margin: 2rem 0 .5rem; }
  a { color: var(--accent); }
  a:focus-visible { outline: 3px solid var(--accent); outline-offset: 2px; }
  code { font-size: .9em; overflow-wrap: anywhere; }
  ul { padding-inline-start: 1.25rem; }
  hr { border: 0; border-top: 1px solid var(--rule); margin: 3rem 0; }"""


def inline(text):
    """Escapes the text, then turns `code`, **bold** and [text](url) into HTML."""
    out = html.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", lambda m: f"<code>{m.group(1)}</code>", out)
    out = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)",
                 lambda m: f'<a href="{html.escape(m.group(2))}">{m.group(1)}</a>', out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
    return out


def markdown(source):
    """The small Markdown subset the sources use: # and ## headings, - lists, paragraphs."""
    blocks, current = [], []
    for line in source.splitlines():
        if line.strip():
            current.append(line)
        elif current:
            blocks.append(current)
            current = []
    if current:
        blocks.append(current)

    out = []
    for block in blocks:
        first = block[0]
        if first.startswith("# "):
            out.append(f"<h1>{inline(first[2:].strip())}</h1>")
        elif first.startswith("## "):
            out.append(f"<h2>{inline(first[3:].strip())}</h2>")
        elif first.startswith("- "):
            items = []
            for line in block:
                if line.startswith("- "):
                    items.append(line[2:].strip())
                else:
                    items[-1] += " " + line.strip()
            out.append("<ul>\n" + "\n".join(f"<li>{inline(i)}</li>" for i in items) + "\n</ul>")
        else:
            out.append(f"<p>{inline(' '.join(l.strip() for l in block))}</p>")
    return "\n".join(out)


def page(name, en_src, he_src, title, description, favicon):
    with open(os.path.join(ROOT, en_src), encoding="utf-8") as f:
        en = markdown(f.read())
    with open(os.path.join(ROOT, he_src), encoding="utf-8") as f:
        he = markdown(f.read())
    other = ('<a href="privacy-policy.html">Privacy policy</a>' if name == "index.html"
             else '<a href="index.html">Bukin Magnifier</a>')
    icon = '<link rel="icon" type="image/png" href="favicon.png">\n' if favicon else ""
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<meta name="description" content="{html.escape(description)}">
<link rel="canonical" href="{SITE_URL}{'' if name == 'index.html' else name}">
{icon}<!-- Generated by scripts/render-site.py from {en_src} and {he_src}: edit those, then regenerate. -->
<style>
{STYLE}
</style>
</head>
<body>
<nav aria-label="Language and pages"><a href="#he" hreflang="he" lang="he">עברית</a>{other}</nav>
<main>
<article id="en" lang="en">
{en}
</article>
<hr>
<article id="he" lang="he" dir="rtl">
{he}
</article>
</main>
</body>
</html>
"""


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    favicon_src = os.path.join(ROOT, "docs/site/favicon.png")
    favicon = os.path.exists(favicon_src)
    for name, (en_src, he_src, title, description) in PAGES.items():
        with open(os.path.join(out, name), "w", encoding="utf-8") as f:
            f.write(page(name, en_src, he_src, title, description, favicon))
    if favicon:
        shutil.copyfile(favicon_src, os.path.join(out, "favicon.png"))
    open(os.path.join(out, ".nojekyll"), "w").close()
    print("wrote", ", ".join(list(PAGES) + (["favicon.png"] if favicon else []) + [".nojekyll"]), "in", out)


if __name__ == "__main__":
    main()
