#!/usr/bin/env python3
"""Puts the chosen launcher icon into the app, the Play assets and the site.

    python3 scripts/make-icon.py <A|B|C> [--root <dir>]

From the icon's description in scripts/icon_art.py it writes (under --root,
the repository by default):

    app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml
        the adaptive icon's layers, as VectorDrawables
    app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml
        the adaptive icon (Android 8+), with the monochrome layer for themed
        icons (Android 13+)
    app/src/main/res/mipmap-{mdpi..xxxhdpi}/ic_launcher.png, ic_launcher_round.png
        PNGs for Android 7.x launchers (48 dp: 48 to 192 px)
    docs/play/assets/icon-512.png
        Play's 512 x 512 icon: the launcher's visible square, full bleed (Play
        rounds the corners itself)
    docs/site/favicon.png
        the site's 96 x 96 favicon (scripts/render-site.py links it)
    docs/play/assets/icon.txt
        the chosen letter, which scripts/store-shots.py uses by default
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import icon_art as art  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Launcher icon {key} ({name}). Generated by scripts/make-icon.py: edit scripts/icon_art.py and rerun. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def write(root, rel, data, binary=False):
    path = os.path.join(root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb" if binary else "w") as f:
        f.write(data)
    return rel


def save_png(root, rel, image):
    path = os.path.join(root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    image.save(path, optimize=True)
    return rel


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("key", choices=sorted(art.DESIGNS))
    ap.add_argument("--root", default=ROOT)
    args = ap.parse_args()
    design = art.DESIGNS[args.key]()
    fg, mono = art.safe_zone_report(design)
    assert fg <= art.SAFE_RADIUS and mono <= art.SAFE_RADIUS, (fg, mono)
    label = f"Launcher icon {design.key} ({design.name})"
    res = "app/src/main/res"
    done = [
        write(args.root, f"{res}/drawable/ic_launcher_background.xml",
              art.vector_xml(design.background, f"{label}: background.", bg_colour=design.bg_colour)),
        write(args.root, f"{res}/drawable/ic_launcher_foreground.xml",
              art.vector_xml(design.foreground, f"{label}: foreground.")),
        write(args.root, f"{res}/drawable/ic_launcher_monochrome.xml",
              art.vector_xml(design.monochrome, f"{label}: monochrome (themed icons use only its shape).",
                             mono=True)),
    ]
    adaptive = ADAPTIVE.format(key=design.key, name=design.name)
    done.append(write(args.root, f"{res}/mipmap-anydpi-v26/ic_launcher.xml", adaptive))
    done.append(write(args.root, f"{res}/mipmap-anydpi-v26/ic_launcher_round.xml", adaptive))
    for density, px in DENSITIES.items():
        done.append(save_png(args.root, f"{res}/mipmap-{density}/ic_launcher.png",
                             art.surface_to_pil(art.render(design, px, mask="rounded"))))
        done.append(save_png(args.root, f"{res}/mipmap-{density}/ic_launcher_round.png",
                             art.surface_to_pil(art.render(design, px, mask="circle"))))
    done.append(save_png(args.root, "docs/play/assets/icon-512.png", art.surface_to_pil(art.render(design, 512))))
    done.append(save_png(args.root, "docs/site/favicon.png",
                         art.surface_to_pil(art.render(design, 96, mask="rounded"))))
    done.append(write(args.root, "docs/play/assets/icon.txt", design.key + "\n"))
    print(f"icon {design.key} ({design.name}):")
    for d in done:
        print("  " + d)


if __name__ == "__main__":
    main()
